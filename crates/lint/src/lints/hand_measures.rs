use syn::ItemImpl;

use crate::finding::{Findings, Found};
use crate::hooks::{Descent, Hooks};
use crate::lint::{Lint, Reads};
use crate::source::Source;

#[derive(Debug)]
pub(crate) struct HandMeasures {
    found: Vec<Found>,
    home: Option<()>,
}

impl HandMeasures {
    const TRAIT: &'static str = "Measure";
    const HOME: &'static str = "pipeline";
}

impl Hooks for HandMeasures {
    fn item_impl(&mut self, item: &ItemImpl) -> Descent {
        let measured = item.trait_.as_ref().and_then(|(_, path, _)| path.segments.last());
        let hand = measured.filter(|last| last.ident == HandMeasures::TRAIT).filter(|_| self.home.is_none());
        self.found.extend(hand.map(|last| {
            Found::spanned(
                last.ident.span(),
                "hand-written impl Measure",
                "declare it in pipeline::measured!; only pipeline joins std types by hand",
            )
        }));
        Descent::Into
    }
}

impl<'file> Lint<'file> for HandMeasures {
    const HEADLINE: &'static str = "a Measure is generated by pipeline::measured!, so its join is fieldwise and lawful by construction; only pipeline joins std types by hand";
    const READS: Reads = Reads::Every;

    type Fact = Findings;

    fn new(source: &'file Source) -> HandMeasures {
        let home = (source.package().name() == HandMeasures::HOME).then_some(());
        HandMeasures { found: Vec::new(), home }
    }

    fn fact(self, source: &'file Source) -> Findings {
        Findings::found(HandMeasures::HEADLINE, source.shown(), self.found)
    }
}
